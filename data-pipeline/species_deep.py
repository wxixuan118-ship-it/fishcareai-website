# ---------------------------------------------------------------- checks

def check(c: dict) -> list[str]:
    """Every [n] must resolve to a reference and every reference must be cited."""
    blob = json.dumps({k: v for k, v in c.items() if k != "references"}, ensure_ascii=False)
    used = {int(n) for n in re.findall(r"\[(\d+)\]", blob)}
    n = len(c["references"])
    problems = [f"cites [{u}] but only {n} references" for u in sorted(used) if u > n]
    problems += [f"reference {i} never cited" for i in range(1, n + 1) if i not in used]
    if not 25 <= len(c["title"]) <= 60:
        problems.append(f"title {len(c['title'])} chars")
    if not 120 <= len(c["description"]) <= 160:
        problems.append(f"description {len(c['description'])} chars")
    if c["keyword"].lower() not in plain(c["intro"][0]).lower():
        problems.append("keyword missing from first paragraph")
    for r in c["related"]:
        if not r["href"].startswith("/"):
            problems.append(f"related link {r['href']} is not site-relative")
    return problems


def article_text(page: str) -> str:
    body = page[page.index('<article class="artc"'):page.index("</article>")]
    body = re.sub(r'<ol class="reflist">.*?</ol>', " ", body, flags=re.S)
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", body))).strip().lower()


def shingles(text: str, n: int = 8) -> set[tuple[str, ...]]:
    words = re.findall(r"[a-z0-9']+", text)
    return {tuple(words[i:i + n]) for i in range(len(words) - n + 1)}


def dupes() -> None:
    """Share of each page's 8-word shingles that also appear on any other rendered page."""
    pages = {p.parent.name: shingles(article_text(p.read_text(encoding="utf-8")))
             for p in sorted(OUT.glob("*/index.html"))}
    worst = 0.0
    for slug, sh in pages.items():
        others = set().union(*(v for k, v in pages.items() if k != slug)) if len(pages) > 1 else set()
        share = 100 * len(sh & others) / max(1, len(sh))
        pair = max(((k, 100 * len(sh & v) / max(1, len(sh))) for k, v in pages.items() if k != slug),
                   key=lambda kv: kv[1], default=("-", 0.0))
        worst = max(worst, share)
        print(f"{slug:24} vs all {share:5.2f}%   closest {pair[0]} {pair[1]:.2f}%")
    print(f"worst {worst:.2f}%")


def update_nginx(slugs: list[str]) -> None:
    conf = NGINX.read_text(encoding="utf-8")
    block_ = NGINX_BEGIN + "".join(
        f"    location = /species/{s} {{\n        try_files /species/{s}/index.html =404;\n    }}\n"
        for s in sorted(slugs)) + NGINX_END
    if NGINX_BEGIN in conf:
        conf = conf[:conf.index(NGINX_BEGIN)] + block_ + conf[conf.index(NGINX_END) + len(NGINX_END):]
    else:
        conf = conf.replace(NGINX_ANCHOR, block_ + "\n" + NGINX_ANCHOR, 1)
    NGINX.write_text(conf, encoding="utf-8")


def load(slug_or_path) -> dict:
    p = slug_or_path if isinstance(slug_or_path, Path) else CONTENT / f"{slug_or_path}.json"
    return json.loads(p.read_text(encoding="utf-8"))


def words(c: dict) -> int:
    parts = [*c["intro"], c["short_answer"]]
    for s in c["sections"]:
        for b in s["blocks"]:
            for k in ("p", "callout", "h3"):
                if k in b:
                    parts.append(b[k])
            for k in ("ul", "ol"):
                parts += b.get(k, [])
    parts += [f["q"] + " " + f["a"] for f in c["faq"]]
    return len(plain(" ".join(parts)).split())


def render(only: list[str]) -> None:
    shell = SHELL.read_text(encoding="utf-8")
    rendered, failed = [], False
    for f in sorted(CONTENT.glob("*.json")):
        c = load(f)
        slug = c["slug"]
        problems = check(c)
        if problems:
            failed = True
            print(f"✗ {slug}: " + "; ".join(problems))
            continue
        if only and slug not in only:
            # Keep routing pages rendered earlier; never route to a page that has no HTML yet.
            if (OUT / slug / "index.html").exists():
                rendered.append(slug)
            continue
        rendered.append(slug)
        (OUT / slug).mkdir(parents=True, exist_ok=True)
        (OUT / slug / "index.html").write_text(render_page(c, shell), encoding="utf-8")
        CHARTS.mkdir(parents=True, exist_ok=True)
        (CHARTS / f"{slug}-care-chart.svg").write_text(chart_svg(c), encoding="utf-8")
        print(f"✓ {slug} (~{words(c)} words, {len(c['references'])} refs)")
    update_nginx(rendered)
    if failed:
        sys.exit(1)


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("render").add_argument("slugs", nargs="*")
    sub.add_parser("check").add_argument("slugs", nargs="*")
    sub.add_parser("dupes")
    args = ap.parse_args()
    if args.cmd == "check":
        bad = False
        for f in sorted(CONTENT.glob("*.json")):
            c = load(f)
            if args.slugs and c["slug"] not in args.slugs:
                continue
            problems = check(c)
            print(("✗ " if problems else "✓ ") + f"{c['slug']} (~{words(c)} words, {len(c['references'])} refs) " + "; ".join(problems))
            bad |= bool(problems)
        sys.exit(1 if bad else 0)
    if args.cmd == "dupes":
        dupes()
    else:
        render(args.slugs)


if __name__ == "__main__":
    main()
