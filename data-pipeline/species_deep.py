# ---------------------------------------------------------------- helpers

def esc(text: str) -> str:
    return html.escape(text, quote=True)


def plain(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"\[\d+\]|<[^>]+>", "", text)).strip()


def ld(obj: dict) -> str:
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False).replace("</", "<\\/") + "</script>"


def cite(text: str, page: str) -> str:
    """[3] or [2][3] → <sup class="cit"> links into the reference list.

    Links carry the page path so crawlers read them as real anchors, not href="#…".
    """
    def sup(m: re.Match) -> str:
        nums = re.findall(r"\[(\d+)\]", m.group(0))
        return '<sup class="cit">' + "".join(f'<a href="{page}#ref-{n}">[{n}]</a>' for n in nums) + "</sup>"
    return re.sub(r"(?:\[\d+\])+", sup, text)


def block(b: dict, page: str, c: dict) -> str:
    if "p" in b:
        return f"<p>{cite(b['p'], page)}</p>"
    if "h3" in b:
        return f"<h3>{esc(b['h3'])}</h3>"
    if "ul" in b:
        return "<ul>\n" + "\n".join(f"  <li>{cite(i, page)}</li>" for i in b["ul"]) + "\n</ul>"
    if "ol" in b:
        return "<ol>\n" + "\n".join(f"  <li>{cite(i, page)}</li>" for i in b["ol"]) + "\n</ol>"
    if "callout" in b:
        variant = b.get("variant", "ok")
        return f'<div class="callout callout-{variant}">{cite(b["callout"], page)}</div>'
    if "table" in b:
        t = b["table"]
        head = "".join(f"<th>{esc(h)}</th>" for h in t["head"])
        rows = "\n".join("<tr>" + "".join(f"<td>{cite(cell, page)}</td>" for cell in r) + "</tr>" for r in t["rows"])
        return f'<table class="ptbl">\n<thead><tr>{head}</tr></thead>\n<tbody>\n{rows}\n</tbody>\n</table>'
    if "chart" in b:
        ch = c["chart"]
        return (f'<figure class="sp-fig">\n  <img src="/assets/species-deep/{c["slug"]}-care-chart.svg" '
                f'alt="{esc(ch["alt"])}" width="1200" height="600" loading="lazy" decoding="async">\n'
                f'  <figcaption>{esc(ch["caption"])}</figcaption>\n</figure>')
    raise ValueError(f"unknown block {b}")


# ---------------------------------------------------------------- care chart

def _band(x0: float, w: float, lo: float, hi: float, vmin: float, vmax: float) -> tuple[float, float]:
    a = x0 + (lo - vmin) / (vmax - vmin) * w
    b = x0 + (hi - vmin) / (vmax - vmin) * w
    return a, max(b - a, 6)


