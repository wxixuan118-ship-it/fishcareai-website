"""Hand-researched species profiles served as static overrides — 2026-10-24.

The species app renders every /species/<slug> page from one template: nine H2s
that all repeat the common name, one paragraph per section, no sources, and a
"Species Related to" block that is empty for most rows. An on-page audit of the
20 profiles that overlap with a competitor's ranking pages scored them 84-93 and
flagged the same template faults on every one (keyword density 5-9%, ~500
words, thin meta, no outbound sources).

These 20 profiles are rewritten by hand from FishBase, Seriously Fish and the
primary literature and served by nginx in place of the app, the same mechanism
as data-pipeline/fish_health_deep.py:

  check [<slug>...]    validate content files without writing anything
  render [<slug>...]   build species/<slug>/index.html and the care chart SVG
                       from data-pipeline/species_deep/<slug>.json, then
                       regenerate the nginx override block
  dupes                pairwise 8-word shingle overlap between rendered pages

Citations are written inline as [n] and point at the page's reference list;
<em>, <strong> and <a href="/..."> are allowed in copy.
"""

