"""Hand-researched fish-health pages served as static overrides — 2026-09-28.

The species app renders ~8,000 /fish-health/ pages from glm-4-flash copy that
lists the same five causes for every species. Google's AI Overview for these
queries leads with the species-specific cause (a bloated guppy is usually
pregnant; a fading flowerhorn is usually the "fader" gene), and our template
pages miss it. blood-parrot-cichlid-pale-color, the one page rewritten by hand
with citations, is also the one with the most clicks.

This script runs a controlled test of that rewrite on the top pages by
impressions:

  select <gsc-export.xlsx>   pair the top 80 pages by impressions, assign one
                             of each pair to "test" at random
                             → reports/fish-health-deep-test-2026-09-28.csv
  fetch <slug>...            snapshot species facts, dates and links from the
                             species app (upstream, not the public URL, which
                             becomes our own page once the override is live)
                             → data-pipeline/fish_health_deep/<slug>.live.json
  check <slug>...            validate content files without writing anything
  render [<slug>...]         build fish-health/<slug>/index.html from
                             data-pipeline/fish_health_deep/<slug>.json and
                             regenerate the nginx override block

Content files hold the researched copy. Citations are written inline as [n]
and point at the page's own references list; <em> and <strong> are allowed.
"""

from __future__ import annotations

import argparse
import csv
import html
import json
import random
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = Path(__file__).resolve().parent / "fish_health_deep"
OUT = ROOT / "fish-health"
SHELL = OUT / "blood-parrot-cichlid-pale-color" / "index.html"
NGINX = ROOT / "nginx.conf"
REPORT = ROOT / "reports" / "fish-health-deep-test-2026-09-28.csv"
UPSTREAM = "https://fishcareai-species-app-b1e198.anysites.app/fish-health/"
SITE = "https://www.fishcareai.com"

SEED = 20260928
MAX_PAGES = 80
MAX_POSITION = 15.0
# Already served as static pages; not part of the test.
STATIC = {"blood-parrot-cichlid-pale-color", "celestial-pearl-danio-black-spots"}

NGINX_BEGIN = "    # BEGIN fish-health deep pages (generated by data-pipeline/fish_health_deep.py)\n"
NGINX_END = "    # END fish-health deep pages\n"
NGINX_ANCHOR = "    # ── Proxy: Species App"

LIKELIHOOD = {"high": ("likelihood-high", "Most Likely"),
              "medium": ("likelihood-medium", "Possible"),
              "low": ("likelihood-low", "Less Common")}
URGENCY_ICON = {"monitor": "🔍", "urgent": "⚠️", "emergency": "🚨"}


# ---------------------------------------------------------------- select

def select(export: Path) -> None:
    from openpyxl import load_workbook

    rows = list(load_workbook(export, read_only=True)["网页"].iter_rows(values_only=True))[1:]
    pages = []
    for url, clicks, impr, ctr, pos in rows:
        m = re.search(r"/fish-health/([a-z0-9-]+)$", url or "")
        if not m or m.group(1) in STATIC or m.group(1) == "fish" or pos > MAX_POSITION:
            continue
        pages.append({"slug": m.group(1), "url": url, "clicks": int(clicks), "impressions": int(impr),
                      "ctr": round(ctr * 100, 2), "position": round(pos, 2)})
    pages.sort(key=lambda r: -r["impressions"])
    pages = pages[:MAX_PAGES]

    rng = random.Random(SEED)
    for i in range(0, len(pages), 2):
        pair = pages[i:i + 2]
        rng.shuffle(pair)
        pair[0]["group"] = "test"
        if len(pair) > 1:
            pair[1]["group"] = "control"

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    with REPORT.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["slug", "group", "impressions", "clicks", "ctr", "position", "url"])
        w.writeheader()
        w.writerows(sorted(pages, key=lambda r: (r["group"], -r["impressions"])))
    for g in ("test", "control"):
        rs = [r for r in pages if r["group"] == g]
        imp, clk = sum(r["impressions"] for r in rs), sum(r["clicks"] for r in rs)
        print(f"{g:8} pages={len(rs)} impressions={imp} clicks={clk} ctr={clk / imp * 100:.2f}% "
              f"avg_pos={sum(r['position'] for r in rs) / len(rs):.2f}")
    print(f"wrote {REPORT.relative_to(ROOT)}")


# ---------------------------------------------------------------- fetch

def _clean(fragment: str) -> str:
    return html.unescape(re.sub(r"<!-- -->|<[^>]+>", "", fragment)).strip()


def fetch(slugs: list[str]) -> None:
    CONTENT.mkdir(parents=True, exist_ok=True)
    for slug in slugs:
        req = urllib.request.Request(UPSTREAM + slug, headers={"User-Agent": "Mozilla/5.0"})
        page = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
        profile = dict(re.findall(r"<tr><td>([^<]+)</td><td[^>]*>(.*?)</td></tr>",
                                  re.search(r'<table class="qf-table">(.*?)</table>', page, re.S).group(1)))
        crumbs = re.findall(r'<a href="([^"]*)"[^>]*>([^<]*)</a>', re.search(r'class="breadcrumb">(.*?)</div>', page, re.S).group(1))
        guide = re.search(r'<a href="((?:https://www\.fishcareai\.com)?/guides/[^"]+)"[^>]*>([^<]+)</a>', page)
        live = {
            "slug": slug,
            "species": _clean(profile["Species"]),
            "scientific": _clean(profile["Scientific"]),
            "water": _clean(profile.get("Water", "")),
            "temp": _clean(profile.get("Temp", "")),
            "ph": _clean(profile.get("pH", "")),
            "care": _clean(profile.get("Care level", "")),
            "fish_hub": next(h for h, _ in crumbs if h.startswith("/fish-health/fish/")),
            "problem": _clean(re.search(r"Problem:</strong>(.*?)</div>", page, re.S).group(1)).replace("\xa0", " ").strip(),
            "category": _clean(re.search(r"Category:</strong>(.*?)</div>", page, re.S).group(1)).replace("\xa0", " ").strip(),
            "urgency": _clean(re.search(r"Urgency:</strong>(.*?)</div>", page, re.S).group(1)).replace("\xa0", " ").strip(),
            "hero": re.search(r'class="sp-hero-img" src="([^"]+)"', page).group(1),
            "species_profile": re.search(r'<a href="(/species/[^"]+)"', page).group(1),
            "guide": {"href": guide.group(1), "label": _clean(guide.group(2))} if guide else None,
            "date_published": re.search(r'"datePublished":"([^"]+)"', page).group(1),
        }
        (CONTENT / f"{slug}.live.json").write_text(json.dumps(live, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"fetched {slug}: {live['species']} / {live['problem']} ({live['urgency']})")


# ---------------------------------------------------------------- render

def cite(text: str) -> str:
    """[3] or [2][3] → <sup class="cit"> links into the reference list."""
    def sup(m: re.Match) -> str:
        nums = re.findall(r"\[(\d+)\]", m.group(0))
        return '<sup class="cit">' + "".join(f'<a href="#ref-{n}">[{n}]</a>' for n in nums) + "</sup>"
    return re.sub(r"(?:\[\d+\])+", sup, text)


def plain(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"\[\d+\]|<[^>]+>", "", text)).strip()


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def ld(obj: dict) -> str:
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False).replace("</", "<\\/") + "</script>"


def steps(items: list[dict]) -> str:
    out = []
    for i, s in enumerate(items, 1):
        tool = f'\n    <div class="step-tool">Recommended: {esc(s["tool"])}</div>' if s.get("tool") else ""
        out.append(f"""<li class="step-item">
  <div class="step-num" aria-hidden="true">{i}</div>
  <div class="step-body">
    <div class="step-action">{esc(s["action"])}</div>
    <p class="step-detail">{cite(s["detail"])}</p>{tool}
  </div>
</li>""")
    return '<ol class="steps-list">\n\n' + "\n\n".join(out) + "\n\n</ol>"


def sidebar_link(href: str, label: str, last: bool = False) -> str:
    return (f'  <div style="margin-bottom:{16 if last else 8}px">\n    <a href="{esc(href)}" style="display:block;text-align:center;'
            'padding:10px;background:var(--card-bg);border:1px solid var(--bd);border-radius:8px;font-size:0.84rem;'
            f'color:var(--p);font-weight:600">{label}</a>\n  </div>')


