def check(c: dict) -> list[str]:
    """Every [n] must resolve to a reference and every reference must be cited."""
    blob = json.dumps({k: v for k, v in c.items() if k != "references"}, ensure_ascii=False)
    used = {int(n) for n in re.findall(r"\[(\d+)\]", blob)}
    n = len(c["references"])
    problems = [f"cites [{u}] but only {n} references" for u in sorted(used) if u > n]
    problems += [f"reference {i} never cited" for i in range(1, n + 1) if i not in used]
    if len(c["title"]) > 60:
        problems.append(f"title {len(c['title'])} chars")
    if len(c["description"]) > 160:
        problems.append(f"description {len(c['description'])} chars")
    return problems


def update_nginx(slugs: list[str]) -> None:
    conf = NGINX.read_text(encoding="utf-8")
    block = NGINX_BEGIN + "".join(
        f"    location = /fish-health/{s} {{\n        try_files /fish-health/{s}/index.html =404;\n    }}\n"
        for s in sorted(slugs)) + NGINX_END
    if NGINX_BEGIN in conf:
        conf = conf[:conf.index(NGINX_BEGIN)] + block + conf[conf.index(NGINX_END) + len(NGINX_END):]
    else:
        conf = conf.replace(NGINX_ANCHOR, block + "\n" + NGINX_ANCHOR, 1)
    NGINX.write_text(conf, encoding="utf-8")


def render(only: list[str]) -> None:
    shell = SHELL.read_text(encoding="utf-8")
    files = sorted(p for p in CONTENT.glob("*.json") if not p.name.endswith(".live.json"))
    rendered, failed = [], False
    for f in files:
        c = json.loads(f.read_text(encoding="utf-8"))
        slug = c["slug"]
        problems = check(c)
        if problems:
            failed = True
            print(f"✗ {slug}: " + "; ".join(problems))
            continue
        if only and slug not in only:
            # Keep routing pages rendered earlier; never route to a page that has no HTML yet.
            if (OUT / slug / "index.html").exists():
                rendered.append(slug)
            continue
        rendered.append(slug)
        live = json.loads((CONTENT / f"{slug}.live.json").read_text(encoding="utf-8"))
        (OUT / slug).mkdir(parents=True, exist_ok=True)
        (OUT / slug / "index.html").write_text(render_page(c, live, shell), encoding="utf-8")
        words = len(plain(" ".join(json.dumps(c, ensure_ascii=False).split())).split())
        print(f"✓ {slug} (~{words} words, {len(c['references'])} refs)")
    update_nginx(rendered)
    if failed:
        sys.exit(1)


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("select").add_argument("export", type=Path)
    sub.add_parser("fetch").add_argument("slugs", nargs="+")
    sub.add_parser("render").add_argument("slugs", nargs="*")
    sub.add_parser("check").add_argument("slugs", nargs="+")
    args = ap.parse_args()
    if args.cmd == "check":
        bad = False
        for slug in args.slugs:
            c = json.loads((CONTENT / f"{slug}.json").read_text(encoding="utf-8"))
            problems = check(c)
            words = len(plain(json.dumps(c, ensure_ascii=False)).split())
            print(("✗ " if problems else "✓ ") + f"{slug} (~{words} words, {len(c['references'])} refs) " + "; ".join(problems))
            bad |= bool(problems)
        sys.exit(1 if bad else 0)
    if args.cmd == "select":
        select(args.export)
    elif args.cmd == "fetch":
        fetch(args.slugs)
    else:
        render(args.slugs)


if __name__ == "__main__":
    main()
